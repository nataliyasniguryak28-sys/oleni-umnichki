  function previousWeight(g, beforeDate){
    const w = g.weights || {};
    const keys = Object.keys(w)
      .filter(k => k < beforeDate)
      .sort();

    if(!keys.length) return null;
    return Number(w[keys[keys.length - 1]]);
  }

